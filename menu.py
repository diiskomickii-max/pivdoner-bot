ITEMS = {}
for cat, items in MENU.items():
    for i in items:
        i["category"] = cat
        ITEMS[i["id"]] = i

TOPPINGS = MENU.get("🧀 Добавки в шаурму", [])
TOPPINGS_MAP = {t["id"]: t for t in TOPPINGS}


def fmt_price(p: float) -> str:
    return f"{p:.2f}".rstrip("0").rstrip(".") + " Br"


def parse_cart_item(key: str) -> dict:
    """
    Разбирает ключ товара корзины:
    - Простой товар: 'doner_firm_400'
    - Шаурма с добавками: 'doner_firm_400+top_cheese_moz+top_jalapeno'
    """
    parts = key.split("+")
    base_id = parts[0]
    base_item = ITEMS.get(base_id)
    if not base_item:
        return None

    name = base_item["name"]
    price = base_item["price"]
    top_names = []

    for tid in parts[1:]:
        t = TOPPINGS_MAP.get(tid) or ITEMS.get(tid)
        if t:
            price += t["price"]
            top_names.append(t["name"])

    if top_names:
        name += f" (+ {', '.join(top_names)})"

    return {
        "key": key,
        "base_id": base_id,
        "name": name,
        "base_name": base_item["name"],
        "price": price,
        "toppings": top_names,
        "topping_ids": parts[1:],
    }


def cart_text(cart: dict) -> tuple:
    """cart: {item_key: qty} -> текст корзины и общая сумма"""
    lines, total = [], 0.0
    for iid, qty in cart.items():
        if qty <= 0:
            continue
        parsed = parse_cart_item(iid)
        if not parsed:
            continue
        s = parsed["price"] * qty
        total += s
        lines.append(f"• {parsed['name']} ×{qty} — {s:.2f} Br")
    lines.append(f"\n💰 Итого: <b>{total:.2f} Br</b>")
    return "\n".join(lines), total


def pickup_ready_text(pickup_time: str) -> str:
    """Время готовности заказа для кухни: когда собрать к приходу клиента."""
    if pickup_time == "Как можно скорее":
        return "ASAP — готовить сейчас"
    try:
        dt = datetime.strptime(pickup_time, "%H:%M")
        ready = dt - timedelta(minutes=15)
        return f"собрать к {pickup_time} (начать {ready.strftime('%H:%M')})"
    except Exception:
        return f"собрать к {pickup_time}"
